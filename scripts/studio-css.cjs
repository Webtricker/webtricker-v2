// Extracts the <style> block of design/studio-dark.html and scopes it under .stu so it cannot touch admin/login.
const fs = require("fs");
const html = fs.readFileSync(__dirname + "/../design/studio-dark.html", "utf8");
const css = html.slice(html.indexOf("<style>", html.indexOf("<title>")) + 7, html.indexOf("</style>", html.indexOf("<title>")));

const SCOPE = ".stu";
function scopeSelector(sel) {
  sel = sel.trim();
  if (!sel) return sel;
  if (sel === ":root" || sel === "html" || sel === "body" || sel === "html, body") return SCOPE;
  if (/^html[.:\[]/.test(sel)) return sel; // html.lenis etc: class toggled by our runtime
  if (sel === "*") return `${SCOPE} *`;
  if (/^\.lenis/.test(sel)) return sel;
  if (/^(::selection|:focus-visible)/.test(sel)) return `${SCOPE} ${sel}`;
  return `${SCOPE} ${sel}`;
}
function scopeBlock(src) {
  let out = "", i = 0;
  while (i < src.length) {
    // copy comments
    if (src.startsWith("/*", i)) { const e = src.indexOf("*/", i) + 2; out += src.slice(i, e); i = e; continue; }
    const open = src.indexOf("{", i);
    if (open < 0) { out += src.slice(i); break; }
    const pre = src.slice(i, open);
    // find matching close
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { const c = src[j]; if (c === "{") depth++; else if (c === "}") depth--; j++; }
    const body = src.slice(open + 1, j - 1);
    const p = pre.trim();
    if (p.startsWith("@keyframes") || p.startsWith("@font-face")) out += `${pre}{${body}}`;
    else if (p.startsWith("@media") || p.startsWith("@supports")) out += `${pre}{${scopeBlock(body)}}`;
    else if (p.startsWith("@")) out += `${pre}{${body}}`;
    else {
      const lead = pre.match(/^\s*(\/\*[\s\S]*?\*\/\s*)*/)[0];
      const selText = pre.slice(lead.length);
      out += `${lead}${selText.split(",").map(scopeSelector).join(", ")}{${body}}`;
    }
    i = j;
  }
  return out;
}
let scoped = scopeBlock(css);
scoped = scoped.replace(/html.on-dark/g, ".stu.on-dark").replace(/.stu .no-gsap/g, ".stu.no-gsap").replace(/.stu .no-swiper/g, ".stu.no-swiper");
// design uses a local Gotu file and a Google Fonts <link>; next/font supplies both
scoped = scoped.replace(/@font-face\s*\{[^}]*Gotu[^}]*\}/, "");
fs.writeFileSync(__dirname + "/../src/studio/studio.css", "/* GENERATED by scripts/studio-css.cjs from design/studio-dark.html. Do not edit by hand. */\n" + scoped);
