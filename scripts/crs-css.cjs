/* Extracts the course-detail (.crs*) rules from the design and scopes them under .stu, appending to studio-extra.css. Idempotent. */
const fs = require("fs");
const design = fs.readFileSync("design/studio-dark-v2.html", "utf8").split(/\r?\n/);
const start = design.findIndex((l) => l.startsWith(".crs-pk {"));
const end = design.findIndex((l, i) => i > start && l.startsWith(".crs-card--pro .crs-probadge"));
let css = design.slice(start, end + 1).join("\n");
css = css.replace(/(^|[{}]\s*)(\.crs[\w-]*)/gm, "$1.stu $2");
css = css.replace(/"Newsreader", Georgia, serif/g, "var(--f-newsreader), Georgia, serif");
const marker = "/* ---- course detail (generated by scripts/crs-css.cjs) ---- */";
const target = "src/studio/studio-extra.css";
let extra = fs.readFileSync(target, "utf8");
if (extra.includes(marker)) {
  extra = extra.slice(0, extra.indexOf(marker));
}
fs.writeFileSync(target, extra.replace(/\s*$/, "\n") + "\n" + marker + "\n" + css + "\n");
console.log("lines", end - start + 1);
